class AssetRegistryEngine {
    constructor() {
        this.modelRoot = './models';
        if (typeof window !== 'undefined') {
            const h = window.location.hostname;
            if (h === 'localhost' || h === '127.0.0.1' || window.location.protocol === 'file:') {
                this.modelRoot = 'https://onyxpure.my.id/models';
            }
        }
        this.usedAssets = new Set();
        this.failedAssets = new Map();
        this.allAssetsSet = new Set(ALL_ASSETS_LIST.map(p => this.normalizePath(p)));
        ACTIVE_HERO_GLBS.forEach(p => this.allAssetsSet.add(this.normalizePath(p)));
        
        // Listen to global image errors to instantly record failed assets
        if (typeof window !== 'undefined') {
            window.addEventListener('error', (e) => {
                const target = e.target;
                if (target && (target.tagName === 'IMG' || target.tagName === 'SOURCE')) {
                    const src = target.src || target.currentSrc;
                    if (src) {
                        this.markFailed(src, 'IMG load error');
                    }
                }
            }, true);
            
            // Expose globally
            window.AssetRegistry = this;
            window.auditAssetUsage = () => this.auditUsage();
        }
    }

    normalizePath(p) {
        if (!p) return '';
        let s = p.replace(/^(\.\/|\/)/, '');
        s = s.replace(/^(models|model)\//, '');
        try {
            s = decodeURIComponent(s);
        } catch (_) {}
        return s.toLowerCase().trim();
    }

    setRoot(root) {
        if (root) {
            this.modelRoot = root.replace(/\/$/, '');
        }
    }

    resolve(path) {
        if (!path) return '';
        // If already full http(s) URL, record and return
        if (path.startsWith('http://') || path.startsWith('https://')) {
            this.markUsed(path);
            return path;
        }

        let clean = path.replace(/^(\.\/|\/)/, '');
        if (clean.startsWith('models/')) clean = clean.slice(7);
        else if (clean.startsWith('model/')) clean = clean.slice(6);

        this.markUsed(clean);

        // Encode segments for spaces (e.g. 'asset game' -> 'asset%20game')
        const segments = clean.split('/').map(seg => encodeURIComponent(decodeURIComponent(seg)));
        return `${this.modelRoot}/${segments.join('/')}`;
    }

    markUsed(path) {
        if (!path) return;
        const norm = this.normalizePath(path);
        this.usedAssets.add(norm);
    }

    markFailed(path, err) {
        if (!path) return;
        const norm = this.normalizePath(path);
        this.failedAssets.set(norm, err || '404 / Network Error');
        console.warn(`[AssetRegistry] Asset load failed: ${norm} (${err})`);
    }

    isUsed(path) {
        return this.usedAssets.has(this.normalizePath(path));
    }

    auditUsage() {
        const totalRegistered = this.allAssetsSet.size;
        let usedCount = 0;
        const categoryStats = {};

        for (const [catName, paths] of Object.entries(ASSET_CATEGORIES)) {
            let catUsed = 0;
            const normList = paths.map(p => this.normalizePath(p));
            normList.forEach(np => {
                if (this.usedAssets.has(np)) catUsed++;
            });
            categoryStats[catName] = {
                total: paths.length,
                used: catUsed,
                percentage: paths.length ? ((catUsed / paths.length) * 100).toFixed(1) + '%' : '100%'
            };
            usedCount += catUsed;
        }

        const overallPct = ((this.usedAssets.size / totalRegistered) * 100).toFixed(1);
        const report = {
            totalAssetsRegistered: totalRegistered,
            uniqueAssetsUsed: this.usedAssets.size,
            overallPercentage: overallPct + '%',
            failedCount: this.failedAssets.size,
            failedAssetsList: Array.from(this.failedAssets.entries()),
            categories: categoryStats
        };

        console.log('%c=== ONYXPURE MASTER ASSET AUDIT REPORT ===', 'color: #38bdf8; font-weight: bold; font-size: 14px;');
        console.log(`Registered: ${totalRegistered} | Bound & Used: ${this.usedAssets.size} (${overallPct}%) | Failed: ${this.failedAssets.size}`);
        console.table(categoryStats);
        if (this.failedAssets.size > 0) {
            console.warn('[AssetRegistry] Failed assets:', report.failedAssetsList);
        } else {
            console.log('%c[AssetRegistry] 100% Asset Integrity: 0 Broken 404s!', 'color: #10b981; font-weight: bold;');
        }

        return report;
    }
}

export const AssetRegistry = new AssetRegistryEngine();
